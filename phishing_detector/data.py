TYPO_TLDS = ["com", "net", "info", "biz", "co", "cc"]


def _rand_str(n: int, alphabet: str = string.ascii_lowercase) -> str:
    return "".join(random.choice(alphabet) for _ in range(n))


def _homoglyph_swap(brand: str) -> str:
    """Swap one character for a visually similar one (classic homograph
    typosquatting tactic, e.g. o->0, l->1, e->3)."""
    swaps = {"o": "0", "l": "1", "i": "1", "e": "3", "a": "4", "s": "5"}
    chars = list(brand)
    candidates = [i for i, c in enumerate(chars) if c in swaps]
    if not candidates:
        return brand
    i = random.choice(candidates)
    chars[i] = swaps[chars[i]]
    return "".join(chars)


def _typo_variants(brand: str) -> str:
    """Apply one random typosquatting edit: insertion, deletion, swap,
    duplication, or homoglyph substitution."""
    op = random.choice(["insert", "delete", "swap", "duplicate", "homoglyph", "hyphen"])
    chars = list(brand)
    if op == "insert" and chars:
        i = random.randint(0, len(chars))
        chars.insert(i, random.choice(string.ascii_lowercase))
    elif op == "delete" and len(chars) > 3:
        i = random.randint(0, len(chars) - 1)
        del chars[i]
    elif op == "swap" and len(chars) > 1:
        i = random.randint(0, len(chars) - 2)
        chars[i], chars[i + 1] = chars[i + 1], chars[i]
    elif op == "duplicate" and chars:
        i = random.randint(0, len(chars) - 1)
        chars.insert(i, chars[i])
    elif op == "homoglyph":
        return _homoglyph_swap(brand)
    elif op == "hyphen" and len(chars) > 2:
        i = random.randint(1, len(chars) - 1)
        chars.insert(i, "-")
    return "".join(chars)


@dataclass
class UrlRecord:
    url: str
    label: int  # 1 = phishing, 0 = legitimate


def _make_legitimate_url(domain: str) -> str:
    sub = random.choice(SUBDOMAIN_TEMPLATES)
    path = random.choice(PATH_TEMPLATES)
    scheme = "https"  # real major sites overwhelmingly serve HTTPS today
    return f"{scheme}://{sub}{domain}{path}"


def _make_phishing_url() -> str:
    """Generate one phishing-style URL using a randomly chosen real tactic."""
    tactic = random.choice([
        "typosquat", "typosquat", "ip_host", "brand_in_subdomain",
        "brand_in_path", "excess_subdomains", "shortener",
        "suspicious_tld", "https_token", "long_random_host",
    ])
    scheme = random.choice(["http", "http", "https"])

    if tactic == "typosquat":
        brand = random.choice(BRAND_KEYWORDS)
        fake = _typo_variants(brand)
        tld = random.choice(TYPO_TLDS)
        path = random.choice(["/login", "/signin", "/verify", "/account/update", ""])
        return f"{scheme}://{fake}.{tld}{path}"

    if tactic == "ip_host":
        ip = ".".join(str(random.randint(1, 254)) for _ in range(4))
        path = random.choice(["/login.php", "/secure/verify", "/account", "/webscr"])
        return f"{scheme}://{ip}{path}"

    if tactic == "brand_in_subdomain":
        brand = random.choice(BRAND_KEYWORDS)
        word = random.choice(RANDOM_WORDS)
        filler = _rand_str(random.randint(4, 8))
        return f"{scheme}://{brand}.{word}-{filler}.com/login"

    if tactic == "brand_in_path":
        brand = random.choice(BRAND_KEYWORDS)
        filler = _rand_str(random.randint(5, 9))
        tld = random.choice(TYPO_TLDS)
        return f"{scheme}://{filler}-portal.{tld}/{brand}/secure/login"

    if tactic == "excess_subdomains":
        brand = random.choice(BRAND_KEYWORDS)
        chain = ".".join(random.choice(RANDOM_WORDS) for _ in range(random.randint(3, 5)))
        filler = _rand_str(6)
        return f"{scheme}://{brand}.{chain}.{filler}.com/"

    if tactic == "shortener":
        from .features import URL_SHORTENERS
        host = random.choice(sorted(URL_SHORTENERS))
        code = _rand_str(7, string.ascii_letters + string.digits)
        return f"{scheme}://{host}/{code}"

    if tactic == "suspicious_tld":
        brand = random.choice(BRAND_KEYWORDS + [""])
        filler = _rand_str(random.randint(6, 10))
        tld = random.choice(sorted(SUSPICIOUS_TLDS))
        host = f"{brand}-{filler}" if brand else filler
        return f"{scheme}://{host}.{tld}/verify"

    if tactic == "https_token":
        brand = random.choice(BRAND_KEYWORDS)
        filler = _rand_str(5)
        return f"http://https-{brand}-{filler}-secure.com/login"

    # long_random_host
    filler = _rand_str(random.randint(18, 30))
    word = random.choice(RANDOM_WORDS)
    return f"{scheme}://{word}-{filler}.net/account/{_rand_str(6)}"


def generate_synthetic_dataset(n_per_class: int = 800, seed: int = 42) -> pd.DataFrame:
    """Build a balanced, tactic-grounded synthetic dataset.

    Legitimate examples are drawn (with repetition + varied paths/subdomains)
    from `LEGITIMATE_DOMAINS`. Phishing examples are generated by applying
    genuine, documented phishing tactics (see `_make_phishing_url`).

    Returns a DataFrame with one `url` column and one `label` column
    (1 = phishing, 0 = legitimate).
    """
    rng = random.Random(seed)
    random.seed(seed)  # module-level helpers above use the global RNG

    legit_records: List[UrlRecord] = []
    seen = set()
    attempts = 0
    while len(legit_records) < n_per_class and attempts < n_per_class * 20:
        attempts += 1
        domain = rng.choice(LEGITIMATE_DOMAINS)
        url = _make_legitimate_url(domain)
        if url in seen:
            continue
        seen.add(url)
        legit_records.append(UrlRecord(url=url, label=0))

    phish_records: List[UrlRecord] = []
    attempts = 0
    while len(phish_records) < n_per_class and attempts < n_per_class * 20:
        attempts += 1
        url = _make_phishing_url()
        if url in seen:
            continue
        seen.add(url)
        phish_records.append(UrlRecord(url=url, label=1))

    all_records = legit_records + phish_records
    rng.shuffle(all_records)
    df = pd.DataFrame([{"url": r.url, "label": r.label} for r in all_records])
    return df


def featurize_dataframe(df: pd.DataFrame) -> pd.DataFrame:
    """Given a DataFrame with a `url` and `label` column, compute the full
    lexical feature matrix and return a DataFrame with FEATURE_NAMES columns
    plus `label` (and `url` retained for reference)."""
    rows = []
    for _, row in df.iterrows():
        feats = extract_features(row["url"])
        feats["label"] = row["label"]
        feats["url"] = row["url"]
        rows.append(feats)
    out = pd.DataFrame(rows)
    return out[FEATURE_NAMES + ["label", "url"]]


def load_csv_dataset(path: str) -> pd.DataFrame:
    """Load an external (real UCI/Kaggle-style) CSV dataset.

    Supports two shapes:
      (a) a `url` column (+ optional `label`) — features are computed here
          with the same extract_features() used everywhere else.
      (b) a CSV that already has one column per FEATURE_NAMES entry plus a
          `label`/`Result`/`class` column — used as-is (only the label
          column is normalized to `label` with 1=phishing, 0=legitimate).

    Returns a DataFrame with FEATURE_NAMES + label (+ url when available),
    matching the shape `featurize_dataframe` produces, so the rest of the
    pipeline (model.py) needs no changes to consume real data.
    """
    raw = pd.read_csv(path)
    cols_lower = {c.lower(): c for c in raw.columns}

    if "url" in cols_lower:
        url_col = cols_lower["url"]
        label_col = None
        for cand in ("label", "class", "result", "y"):
            if cand in cols_lower:
                label_col = cols_lower[cand]
                break
        df = pd.DataFrame({"url": raw[url_col]})
        if label_col is not None:
            df["label"] = _normalize_labels(raw[label_col])
        else:
            raise ValueError(
                "CSV has a 'url' column but no recognizable label column "
                "(expected one of: label, class, result, y)."
            )
        return featurize_dataframe(df)

    # Shape (b): already-featurized CSV (e.g. UCI 'Phishing Websites' style)
    missing = [f for f in FEATURE_NAMES if f not in raw.columns]
    if missing:
        raise ValueError(
            "CSV does not have a 'url' column, and is missing expected "
            f"feature columns to be used as a pre-featurized dataset: {missing}. "
            "Provide either a raw 'url' (+ label) column, or a CSV whose "
            f"columns match phishing_detector.features.FEATURE_NAMES: {FEATURE_NAMES}"
        )
    label_col = None
    for cand in ("label", "class", "result", "y"):
        if cand in cols_lower:
            label_col = cols_lower[cand]
            break
    if label_col is None:
        raise ValueError("Featurized CSV is missing a label column (label/class/result/y).")

    out = raw[FEATURE_NAMES].copy()
    out["label"] = _normalize_labels(raw[label_col])
    if "url" in raw.columns:
        out["url"] = raw["url"]
    else:
        out["url"] = ""
    return out


def _normalize_labels(series: pd.Series) -> pd.Series:
    """Normalize a label column to 1=phishing / 0=legitimate.

    Handles common encodings seen in real datasets: {1,0}, {1,-1} (UCI uses
    -1 for legitimate, 1 for phishing), {'phishing','legitimate'}, {'bad','good'}.
    """
    if series.dtype == object:
        mapped = series.str.strip().str.lower().map({
            "phishing": 1, "phish": 1, "bad": 1, "malicious": 1, "1": 1,
            "legitimate": 0, "legit": 0, "good": 0, "benign": 0, "0": 0, "-1": 0,
        })
        if mapped.isna().any():
            raise ValueError(f"Could not normalize label values: {series.unique()}")
        return mapped.astype(int)
    numeric = series.astype(int)
    if set(numeric.unique()) <= {1, -1}:
        return numeric.map({1: 1, -1: 0})
    return numeric
