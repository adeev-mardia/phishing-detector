"""Dataset construction for the phishing URL classifier.

Two sources of data are supported:

1. `generate_synthetic_dataset()` — because this sandbox's network egress is
   restricted (no access to kaggle.com / UCI's site / huggingface.co), we
   cannot download the literal UCI/Kaggle "Phishing Websites" dataset here.
   Instead we build a large, tactic-grounded synthetic dataset:
     - Legitimate examples: a hardcoded list of 200+ real, well-known
       domains (varied categories: tech, finance, government, education,
       retail, media, etc.), wrapped in realistic-looking URLs (paths,
       query strings, subdomains like www/docs/support).
     - Phishing examples: generated by programmatically APPLYING real,
       documented phishing tactics to those same brand names and to
       randomly generated look-alike domains: typosquatting (character
       insertion/deletion/swap/homoglyph-style substitution), IP-address
       hosts, brand name stuffed into a subdomain/path on an unrelated
       domain, excessive subdomains, URL-shortener hosts, suspicious TLDs,
       hyphenated brand mimicry, https-token-in-domain tricks, etc.
   This keeps the label grounded in genuine phishing tactics rather than
   arbitrary noise.

2. `load_csv_dataset(path)` — loads a REAL external CSV (e.g. an actual
   downloaded UCI/Kaggle phishing dataset) with a `url` column (raw URLs,
   features are computed with features.extract_features) OR a CSV that
   already has one column per name in features.FEATURE_NAMES plus a
   `label` column (1 = phishing, 0 = legitimate) — the common shape UCI's
   "Phishing Websites" CSV mirrors, so it can be dropped in with
   `--csv path/to/real_dataset.csv` and used with ZERO changes to the
   feature-extraction or model code.
"""

